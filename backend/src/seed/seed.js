export async function runSeed() {
  console.log('--- Starting Demo Data Seed ---');
  if (!isFirebaseConfigured || !firestore) {
    console.error('Firebase Admin is not configured. Cannot seed Firestore.');
    process.exit(1);
  }

  // 1. Seed Students
  console.log(`Seeding ${DEMO_STUDENTS.length} fictional students...`);
  for (const student of DEMO_STUDENTS) {
    await firestore.collection('users').doc(student.uid).set({
      ...student,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString()
    }, { merge: true });
  }
  console.log('✔ Successfully seeded fictional students with visible Demo flag.');

  // 2. Seed Book Listings
  console.log(`Seeding ${DEMO_LISTINGS.length} fictional book listings...`);
  for (const listing of DEMO_LISTINGS) {
    await firestore.collection('listings').doc(listing.id).set({
      ...listing,
      createdAt: new Date(Date.now() - Math.floor(Math.random() * 7 * 86400000)).toISOString(),
      updatedAt: new Date().toISOString()
    }, { merge: true });
  }
  console.log('✔ Successfully seeded fictional book listings with visible Demo badge.');

  console.log('--- Demo Data Seed Completed Successfully ---');
}

// Auto-run if executed directly
if (process.argv[1]?.endsWith('seed.js')) {
  runSeed().then(() => process.exit(0)).catch(err => {
    console.error('Seed error:', err);
    process.exit(1);
  });
}

